/* ---------------- 路径类型与查找 ---------------- */

type Join<K extends string, P extends string> = P extends '' ? K : `${K}.${P}`
type Paths<T> = T extends string ? '' : { [K in keyof T & string]: Join<K, Paths<T[K]>> }[keyof T & string]
export type TKey = Paths<Dict>

function lookup(d: Dict, key: string): string {
  let cur: unknown = d
  for (const part of key.split('.')) {
    if (cur && typeof cur === 'object') cur = (cur as Record<string, unknown>)[part]
    else return key
  }
  return typeof cur === 'string' ? cur : key
}

function format(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

type TFn = (key: TKey, vars?: Record<string, string | number>) => string

type I18nCtx = {
  lang: Lang
  setLang: (l: Lang) => void
  t: TFn
}

const Ctx = createContext<I18nCtx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang)

  const setLang = (l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      /* ignore */
    }
  }

  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'
    document.title = lookup(lang === 'zh' ? zh : en, 'meta.title')
  }, [lang])

  const t = useMemo<TFn>(() => {
    const d = lang === 'zh' ? zh : en
    return (key, vars) => format(lookup(d, key), vars)
  }, [lang])

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useI18n(): I18nCtx {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n must be used within I18nProvider')
  return v
}

/** 预设数据的中英双字段取值：{ label, labelEn } → 当前语言文本 */
export function pickLabel(lang: Lang, o: { label: string; labelEn?: string }): string {
  return lang === 'en' && o.labelEn ? o.labelEn : o.label
}

/** 预设数据的中英双字段取值：{ note, noteEn } → 当前语言文本 */
export function pickNote(lang: Lang, o: { note?: string; noteEn?: string }): string {
  return lang === 'en' && o.noteEn ? o.noteEn : (o.note ?? '')
}

